def phys_ooo(t):
    if has(t, "физических моделей", "моделей:"):
        return ["6"], "физические модели"
    if has(t, "принцип") or (has(t, "схем") and has(t, "устройств")):
        return ["9"], "технические устройства"
    if t.startswith("использовать") and has(t, "понят"):
        return ["3"], "понятия"
    if has(t, "различать явления", "распознавать проявление"):
        return ["2"], "распознавание явлений"
    if t.startswith("описывать"):
        return ["4"], "описание через величины"
    if t.startswith("характеризовать"):
        return ["3"], "законы"
    if t.startswith("объяснять"):
        return ["7"], "объяснение"
    if has(t, "расчётные задачи", "расчетные задачи"):
        return ["8"], "расчётные задачи"
    if has(t, "распознавать проблемы", "опыты", "измерени", "исследование", "техники безопасности"):
        return ["5"], "методы познания, эксперимент"
    if has(t, "принцип"):
        return ["9"], "технические устройства"
    if has(t, "практического использования"):
        return ["10"], "применение в жизни, безопасность"
    if has(t, "источник", "литератур", "сообщени"):
        return ["11"], "работа с информацией"
    if has(t, "в группе"):
        return [], "работа в группе — в требованиях ОГЭ нет"
    return None, ""


def phys_soo(t):
    if has(t, "роль и место физики"):
        return [], "роль физики в картине мира — в требованиях ЕГЭ нет"
    if has(t, "границы примен") and has(t, "модел"):
        return ["4"], "границы применимости моделей"
    if t.startswith("распознавать"):
        return ["1"], "распознавание и объяснение явлений"
    if t.startswith("описывать"):
        return ["2"], "понятия и величины"
    if t.startswith("анализировать") or t.startswith("определять направление") or t.startswith("строить"):
        return ["3"], "применение законов"
    if has(t, "принципы действия"):
        return [], "принципы действия устройств — в требованиях ЕГЭ нет"
    if has(t, "эксперимент", "измерени", "исследовать зависимост", "безопасного труда"):
        return ["7"], "методы познания"
    if has(t, "расчётные задачи", "расчетные задачи"):
        return ["5"], "расчётные задачи"
    if has(t, "качественные задачи"):
        return ["6"], "качественные задачи"
    if has(t, "информационные технологии"):
        return ["9"], "работа с информацией"
    if has(t, "вклада"):
        return [], "вклад учёных — в требованиях ЕГЭ нет"
    if has(t, "повседневной жизни"):
        return ["8"], "безопасность, экология"
    if has(t, "в группе"):
        return [], "работа в группе — в требованиях ЕГЭ нет"
    return None, ""


out = {}
for r in recs:
    if r["type"] != "requirement" or r.get("is_group") or r["subject"] not in ("history", "physics"):
        continue
    t = re.sub(r"\s+", " ", r["text"].lower()).replace("- ", "")
    g = r["code"].split(".")[0]
    exam = "oge" if r["part"] == "OOO" else "ege"
    if r["subject"] == "history":
        codes, why = (hist_ooo if r["part"] == "OOO" else hist_soo)(t, g)
    else:
        codes, why = (phys_ooo if r["part"] == "OOO" else phys_soo)(t)
    method = "rule"
    if r["id"] in ovr:
        codes, why, method = ovr[r["id"]], "ручная правка", "manual"
    if codes is None:
        codes, why, method = [], "правило не сработало", "none"
    ids = [f'{r["part"]}.{r["subject"]}.{exam}.req.{c}' for c in codes]
    for i in ids:
        assert i in byid, i
    out[r["id"]] = dict(e=ids, why=why, m=method)

json.dump(out, open("/home/claude/nav/req_out.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("требований", len(out), "без правила", sum(1 for v in out.values() if v["m"] == "none"),
      "без аналога", sum(1 for v in out.values() if not v["e"]))
