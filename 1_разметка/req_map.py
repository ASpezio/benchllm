#!/usr/bin/env python3
"""Связь «требование класса (умение) → требование ОГЭ/ЕГЭ».

История: основа — группа требования (одинаковые группы во всех классах уровня), уточнение по
ключевым словам умения. Физика: по ключевым словам (смысл кода сохраняется между классами).
Пустой список = в требованиях экзамена прямого аналога нет (это результат, а не пропуск).
Ручные правки — req_overrides.json: {"<id требования класса>": ["<код экзамена>", ...]}.
"""
import json, os, re, csv
from collections import defaultdict

REC = "/mnt/user-data/uploads/аа/разметка/records.jsonl"
recs = [json.loads(l) for l in open(REC, encoding="utf-8")]
byid = {r["id"]: r for r in recs}
OVR = "/home/claude/nav/req_overrides.json"
ovr = json.load(open(OVR, encoding="utf-8")) if os.path.exists(OVR) else {}


def has(t, *ws):
    return any(w in t for w in ws)


def hist_ooo(t, g):
    if g == "1":
        return ["1"], "хронология"
    if g == "2":
        if has(t, "систематиз", "группир"):
            return [], "систематизация фактов — в требованиях ОГЭ нет"
        return ["4"], "знание фактов"
    if g == "3":
        return ["11"], "карта"
    if g == "4":
        if has(t, "анализировать текстовые", "представлять историческую информацию", "в виде таблиц"):
            return ["12"], "анализ текст./визуальных источников, таблицы"
        if has(t, "основные типы", "тип и вид", "виды письменных", "различать основные", "различать памятники", "различать источники", "в дополнение"):
            return ["9"], "типы источников"
        return ["10"], "работа с источником"
    if g == "5":
        if has(t, "памятник", "культур"):
            return ["2", "4"], "описание памятников культуры"
        return ["4"], "рассказ/описание"
    if g == "6":
        if has(t, "существенные черты", "характерные признаки", "иллюстрировать"):
            return ["5"], "черты и признаки"
        if has(t, "смысл") and has(t, "понят"):
            return ["3"], "понятия"
        if has(t, "причин", "следств", "взаимосвяз"):
            return ["6"], "причины и следствия"
        if has(t, "сравн", "сопоставлен", "синхрониз"):
            return ["7"], "сравнение"
        if has(t, "культур", "быт", "нрав"):
            return ["2"], "культура и быт"
        return ["5"], "черты и признаки"
    if g == "7":
        return ["8"], "оценки и точка зрения"
    if g == "8":
        if has(t, "понят"):
            return ["3"], "понятия"
        if has(t, "поиск"):
            return ["13"], "поиск информации"
        if has(t, "проект"):
            return [], "учебные проекты — в требованиях ОГЭ нет"
        if has(t, "аргумент"):
            return ["8", "14"], "оценка наследия"
        return ["2", "14"], "памятники, наследие"
    return None, ""


