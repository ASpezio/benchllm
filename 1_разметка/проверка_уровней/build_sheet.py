#!/usr/bin/env python3
"""Лист для проверки разметки «глагол → уровень Блума» вторым разметчиком.

Требования ФОП (история и физика, ООО и СОО) делятся на действия: главное до «:», уточнения после — по «;» и по запятой
перед инфинитивом. Для каждого действия — глагол, уровень по словарю (авто) и пометка «неоднозначный» для глаголов,
которые бывают на разных уровнях («объяснять», «определять», «использовать»…). Столбцы «уровень_1» и «уровень_2»
заполняют два человека независимо; kappa.py считает согласие.

  python3 build_sheet.py            → уровни_действий.csv (UTF-8 с BOM, открывается в Excel)
"""
import csv
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REC = os.path.join(HERE, "..", "records.jsonl")
LEVELS = ["запомнить", "понять", "применить", "анализировать", "оценить", "создать", "не_когнитивное"]
VERBS = {
    "запомнить": ["называть", "перечислять", "знать", "воспроизводить", "указывать", "показывать"],
    "понять": ["описывать", "характеризовать", "рассказывать", "различать", "распознавать", "приводить", "раскрывать",
               "трактовать", "интерпретировать", "представлять", "демонстрировать", "пересказывать", "переводить"],
    "применить": ["решать", "применять", "вычислять", "проводить", "выполнять", "записывать", "подставлять", "находить",
                  "собирать", "строить", "осуществлять", "измерять", "использовать", "локализовать", "читать"],
    "анализировать": ["анализировать", "сравнивать", "выявлять", "систематизировать", "классифицировать", "выделять",
                      "группировать", "исследовать", "планировать", "сопоставлять", "соотносить", "устанавливать"],
    "оценить": ["оценивать", "аргументировать", "обосновывать", "высказывать", "проверять", "учитывать", "критически"],
    "создать": ["создавать", "конструировать", "разрабатывать", "составлять", "формулировать", "предлагать", "моделировать"],
    "не_когнитивное": ["соблюдать", "работать", "распределять", "следить", "участвовать", "выстраивать", "проявлять"],
}
AMBIG = {"объяснять", "определять", "использовать", "устанавливать", "формулировать", "делать", "выделять", "указывать",
         "характеризовать", "представлять", "находить", "приводить", "описывать"}
V2L = {v: lvl for lvl, vs in VERBS.items() for v in vs}
V2L.update({"объяснять": "понять", "определять": "применить", "делать": "оценить", "понимать": "понять", "излагать": "понять",
            "привлекать": "применить", "извлекать": "применить", "фиксировать": "применить", "отвечать": "применить",
            "выбирать": "анализировать", "обобщать": "анализировать", "узнавать": "запомнить"})
# существительные: требования экзамена («знание…», «умение проводить анализ…») и обобщённые глаголы («проводить сопоставление»)
NOUNS = {"знание": "запомнить", "понимание": "понять", "применение": "применить", "использование": "применить",
         "анализ": "анализировать", "рассмотрение": "анализировать", "сопоставление": "анализировать", "сравнение": "анализировать",
         "оценка": "оценить", "аргументация": "оценить", "поиск": "применить", "работа": "применить", "измерение": "применить",
         "наблюдение": "применить", "опыт": "применить", "исследование": "анализировать", "объяснение": "понять", "описание": "понять"}
GENERIC = {"проводить", "осуществлять", "выполнять"}
AMBIG |= GENERIC


def level(action, v):
    words = re.findall(r"[а-яё\-]+", action.lower())[:5]
    if v in GENERIC or v not in V2L:
        for w in words:
            for n, lvl in NOUNS.items():
                if w.startswith(n[:-1]):
                    return lvl
    return V2L.get(v, "?")


def verb(s):
    w = re.findall(r"[а-яё\-]+", s.lower())
    for x in w[:3]:
        if x.endswith(("ть", "ться", "тись")):
            return x.removesuffix("ся")
    return w[0] if w else ""


def split_actions(text):
    t = re.sub(r"\s+", " ", text.replace("- ", "")).strip()
    head, _, tail = t.partition(":")
    parts = [head]
    for chunk in re.split(r";", tail):
        sub = re.split(r",\s+(?=[а-яё]+(?:ть|ться)\b)", chunk)
        parts += [x for x in sub if x.strip()]
    return [p.strip(" .,") for p in parts if p.strip(" .,")]


def main():
    rows = []
    for l in open(REC, encoding="utf-8"):
        r = json.loads(l)
        if r.get("type") != "requirement" or r.get("subject") not in ("history", "physics"):
            continue
        for i, a in enumerate(split_actions(r["text"])):
            v = verb(a)
            rows.append({"id": f"{r['id']}#{i}", "предмет": r["subject"], "уровень_школы": r["part"], "класс": r.get("grade") or "",
                         "код": r.get("code") or "", "главное": "да" if i == 0 else "", "действие": a, "глагол": v,
                         "уровень_авто": level(a, v), "неоднозначный": "да" if v in AMBIG else "",
                         "уровень_1": "", "уровень_2": "", "комментарий": ""})
    out = os.path.join(HERE, "уровни_действий.csv")
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter=";")
        w.writeheader(); w.writerows(rows)
    from collections import Counter
    for s in ("history", "physics"):
        rs = [r for r in rows if r["предмет"] == s]
        c = Counter(r["уровень_авто"] for r in rs)
        print(s, len(rs), "действий;", ", ".join(f"{k} {v / len(rs):.0%}" for k, v in c.most_common()),
              f"; неоднозначных глаголов {sum(1 for r in rs if r['неоднозначный']) / len(rs):.0%}")
    print("→", out)


if __name__ == "__main__":
    main()
